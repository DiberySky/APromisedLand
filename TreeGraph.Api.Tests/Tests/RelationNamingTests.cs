using TreeGraph.Api.NodeEavSky.Services;
using Xunit;

namespace TreeGraph.Api.Tests.Tests;

/// <summary>
/// relation_type 解析与校验规则（R6）：
/// 显式优先 → 驼峰转 snake 回退 → 自动名报错；字符集 / 长度 / 保留类型校验。
/// </summary>
public class RelationNamingTests
{
    [Theory]
    [InlineData("FEEDS_LINE", "feeds_line")]
    [InlineData("  MEMBER_OF  ", "member_of")]
    [InlineData("already_snake", "already_snake")]
    public void Resolve_Explicit_WinsAndNormalizes(string input, string expected)
    {
        var (value, error) = RelationNaming.Resolve(input, "SomeCamelName", true);
        Assert.Null(error);
        Assert.Equal(expected, value);
    }

    [Theory]
    [InlineData("UserDept", "user_dept")]
    [InlineData("deptId", "dept_id")]
    [InlineData("equipment2Name", "equipment2_name")]
    [InlineData("HTTPStatus", "http_status")]
    [InlineData("ABCTest", "abc_test")]
    [InlineData("Name", "name")]
    public void Resolve_CamelCaseName_DerivesSnakeCase(
        string attributeName, string expected)
    {
        var (value, error) = RelationNaming.Resolve(null, attributeName, true);
        Assert.Null(error);
        Assert.Equal(expected, value);
    }

    [Fact]
    public void Resolve_AutoGeneratedName_ReturnsCannotDerive()
    {
        var (value, error) = RelationNaming.Resolve(null, "attr_3f9a2b1c8d4e", false);
        Assert.Null(value);
        Assert.Equal(RelationNaming.CannotDeriveMessage, error);
    }

    [Fact]
    public void Resolve_ExplicitInvalid_ReturnsError()
    {
        var (value, error) = RelationNaming.Resolve("bad-type", "UserDept", true);
        Assert.Null(value);
        Assert.Contains("relation_type", error);
    }

    [Theory]
    [InlineData("_lead")]
    [InlineData("a-b")]
    [InlineData("a.b")]
    [InlineData("用户")]
    [InlineData("   ")]
    [InlineData("1abc")]
    public void Validate_RejectsInvalidCharset(string value)
    {
        Assert.NotNull(RelationNaming.Validate(value));
    }

    [Theory]
    [InlineData("parent_of")]
    [InlineData("connects_to")]
    [InlineData("line_segment")]
    public void Validate_RejectsReservedTypes(string value)
    {
        var error = RelationNaming.Validate(value);
        Assert.NotNull(error);
        Assert.Contains("保留", error);
    }

    [Fact]
    public void Validate_100Chars_IsAllowed()
    {
        Assert.Null(RelationNaming.Validate(new string('a', 100)));
        Assert.NotNull(RelationNaming.Validate(new string('a', 101)));
    }

    [Fact]
    public void Validate_UppercaseInput_IsAcceptedAfterLowering()
    {
        Assert.Null(RelationNaming.Validate("BelongsTo"));
    }
}
